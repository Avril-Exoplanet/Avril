private struct EventEvidenceTimeline: View {
    let events: [JSONValue]
    var body: some View {
        if events.isEmpty {
            Text("NO PER-EVENT EVIDENCE IN THE COMPACT RESULT")
                .font(.nova(size: 9, weight: .medium, design: .monospaced)).foregroundStyle(NovaTheme.inkTertiary)
                .frame(maxWidth: .infinity, maxHeight: .infinity).background(NovaTheme.surfaceMuted)
        } else {
            Canvas { context, size in
                let times = events.compactMap { $0["center_btjd"]?.doubleValue ?? $0["time"]?.doubleValue }
                guard let minimum = times.min(), let maximum = times.max() else { return }
                let left: CGFloat = 35, right: CGFloat = 20, y = size.height * 0.52
                var axis = Path(); axis.move(to: .init(x: left, y: y)); axis.addLine(to: .init(x: size.width - right, y: y))
