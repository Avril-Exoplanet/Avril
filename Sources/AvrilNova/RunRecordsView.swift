    private func copyExecutionLog(_ log: ExecutionLogDocument) {
        let text = log.events.map { event in
            var lines = ["[\(event.seq ?? 0)] \(event.time ?? "—") · \(event.stage ?? "unknown") · \(event.level ?? "info") · \(event.title ?? "")"]
            if let message = event.message, !message.isEmpty { lines.append(message) }
            if let command = event.command, !command.isEmpty { lines.append("$ \(command)") }
            if let metrics = event.metrics, !metrics.isEmpty {
                lines.append(metrics.keys.sorted().map { "\($0)=\(metrics[$0]?.compactDescription ?? "—")" }.joined(separator: " · "))
            }
            return lines.joined(separator: "\n")
        }.joined(separator: "\n\n")
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

