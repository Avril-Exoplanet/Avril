                for (index, event) in events.enumerated() {
                    guard let time = event["center_btjd"]?.doubleValue ?? event["time"]?.doubleValue else { continue }
                    let x = left + CGFloat((time - minimum) / max(maximum - minimum, 1e-12)) * (size.width - left - right)
                    let compromised = event["critical_gap_compromise"]?.boolValue == true
                    let ses = abs(event["ses_like"]?.doubleValue ?? event["snr"]?.doubleValue ?? 0)
                    let radius = min(8, 3 + CGFloat(ses / 3))
                    let color = compromised ? NovaTheme.red : NovaTheme.cyan
                    let marker = Path(ellipseIn: CGRect(x: x - radius, y: y - radius, width: radius * 2, height: radius * 2))
                    context.fill(marker, with: .color(color))
                    let sector = event["segment"]?.intValue ?? event["sector"]?.intValue ?? index + 1
                    context.draw(Text("S\(sector)").font(.nova(size: 8, design: .monospaced)).foregroundColor(NovaTheme.inkSecondary), at: .init(x: x, y: index.isMultiple(of: 2) ? y - 25 : y + 25))
                }
                context.draw(Text(String(format: "BTJD %.1f", minimum)).font(.nova(size: 7.5, design: .monospaced)).foregroundColor(NovaTheme.inkTertiary), at: .init(x: left, y: size.height - 12), anchor: .leading)
                context.draw(Text(String(format: "BTJD %.1f", maximum)).font(.nova(size: 7.5, design: .monospaced)).foregroundColor(NovaTheme.inkTertiary), at: .init(x: size.width - right, y: size.height - 12), anchor: .trailing)
            }
            .background(NovaTheme.surfaceMuted)
        }
    }
}

