private struct PhaseFoldEvidencePlot: View {
    let bins: [[Double]]
    let points: [LightCurvePoint]
    let periodDays: Double?
    let epochBTJD: Double?
    let durationHours: Double?
    let tint: Color

    private struct DisplayBin {
        let phase: Double
        let fluxPPM: Double
        let lowerPPM: Double
        let upperPPM: Double
        let samples: Int
    }

    private var displayBins: [DisplayBin] {
        let supplied = bins.compactMap { row -> DisplayBin? in
            guard row.count >= 2, row[0].isFinite, row[1].isFinite else { return nil }
            let lower = row.count >= 3 && row[2].isFinite ? row[2] : row[1]
            let upper = row.count >= 4 && row[3].isFinite ? row[3] : row[1]
            let samples = row.count >= 5 && row[4].isFinite ? max(0, Int(row[4])) : 0
            return DisplayBin(phase: row[0], fluxPPM: row[1], lowerPPM: lower, upperPPM: upper, samples: samples)
        }
        if !supplied.isEmpty { return supplied.sorted { $0.phase < $1.phase } }
        guard let periodDays, periodDays.isFinite, periodDays > 0,
              let epochBTJD, epochBTJD.isFinite, !points.isEmpty else { return [] }

        let transitFraction = max((durationHours ?? 2) / 24 / periodDays, 0.0002)
        let halfWindow = min(0.18, max(0.025, transitFraction * 7))
        let binCount = 100
        var buckets = Array(repeating: [Double](), count: binCount)
        for point in points where point.time.isFinite && point.flux.isFinite {
            var phase = ((point.time - epochBTJD) / periodDays).truncatingRemainder(dividingBy: 1)
            if phase < -0.5 { phase += 1 }
            if phase >= 0.5 { phase -= 1 }
            guard abs(phase) <= halfWindow else { continue }
            let normalized = (phase + halfWindow) / (2 * halfWindow)
            let index = min(binCount - 1, max(0, Int(normalized * Double(binCount))))
            buckets[index].append((point.flux - 1) * 1_000_000)
        }
        return buckets.enumerated().compactMap { index, values in
            guard values.count >= 2 else { return nil }
            let median = Self.median(values)
            let mad = Self.median(values.map { abs($0 - median) })
            let sigma = 1.4826 * mad / sqrt(Double(values.count))
            let phase = -halfWindow + (Double(index) + 0.5) / Double(binCount) * 2 * halfWindow
            return DisplayBin(phase: phase, fluxPPM: median, lowerPPM: median - sigma, upperPPM: median + sigma, samples: values.count)
        }
    }

    var body: some View {
        let rows = displayBins
        if rows.isEmpty {
            Text("NO VERIFIED SAMPLES AVAILABLE FOR THIS FOLD\nNo synthetic curve is shown.")
                .multilineTextAlignment(.center).font(.nova(size: 9, weight: .medium, design: .monospaced)).foregroundStyle(NovaTheme.inkTertiary)
                .frame(maxWidth: .infinity, maxHeight: .infinity).background(NovaTheme.surfaceMuted)
        } else {
            GeometryReader { _ in
                Canvas { context, size in
                    guard let xMin = rows.map(\.phase).min(), let xMax = rows.map(\.phase).max(),
                          let rawYMin = rows.map(\.lowerPPM).min(), let rawYMax = rows.map(\.upperPPM).max() else { return }
                    let yPadding = max((rawYMax - rawYMin) * 0.12, 5)
                    let yMin = rawYMin - yPadding, yMax = rawYMax + yPadding
                    let left: CGFloat = 54, right: CGFloat = 14, top: CGFloat = 16, bottom: CGFloat = 34
                    for index in 0...4 {
                        let x = left + (size.width - left - right) * CGFloat(index) / 4
                        let y = top + (size.height - top - bottom) * CGFloat(index) / 4
                        var vertical = Path(); vertical.move(to: .init(x: x, y: top)); vertical.addLine(to: .init(x: x, y: size.height - bottom))
                        var horizontal = Path(); horizontal.move(to: .init(x: left, y: y)); horizontal.addLine(to: .init(x: size.width - right, y: y))
                        context.stroke(vertical, with: .color(NovaTheme.border.opacity(0.65)), lineWidth: 0.6)
                        context.stroke(horizontal, with: .color(NovaTheme.border.opacity(0.65)), lineWidth: 0.6)
                        let phaseLabel = xMin + (xMax - xMin) * Double(index) / 4
                        let fluxLabel = yMax - (yMax - yMin) * Double(index) / 4
                        context.draw(Text(String(format: "%.3f", phaseLabel)).font(.nova(size: 7.5, design: .monospaced)).foregroundColor(NovaTheme.inkTertiary), at: .init(x: x, y: size.height - 16))
                        context.draw(Text(String(format: "%.0f", fluxLabel)).font(.nova(size: 7.5, design: .monospaced)).foregroundColor(NovaTheme.inkTertiary), at: .init(x: 28, y: y))
                    }
                    func project(_ phase: Double, _ flux: Double) -> CGPoint {
                        let x = left + CGFloat((phase - xMin) / max(xMax - xMin, 1e-12)) * (size.width - left - right)
                        let y = size.height - bottom - CGFloat((flux - yMin) / max(yMax - yMin, 1e-12)) * (size.height - top - bottom)
                        return .init(x: x, y: y)
                    }
                    var band = Path()
                    for (index, row) in rows.enumerated() {
                        let point = project(row.phase, row.upperPPM)
                        index == 0 ? band.move(to: point) : band.addLine(to: point)
                    }
                    for row in rows.reversed() { band.addLine(to: project(row.phase, row.lowerPPM)) }
                    band.closeSubpath()
                    context.fill(band, with: .color(tint.opacity(0.14)))
                    var path = Path()
                    for (index, row) in rows.enumerated() {
                        let point = project(row.phase, row.fluxPPM)
                        if index == 0 { path.move(to: point) } else { path.addLine(to: point) }
                    }
                    context.stroke(path, with: .color(tint), lineWidth: 1.6)
                    if xMin < 0, xMax > 0 {
                        let x = project(0, yMin).x
                        var epoch = Path(); epoch.move(to: .init(x: x, y: top)); epoch.addLine(to: .init(x: x, y: size.height - bottom))
                        context.stroke(epoch, with: .color(NovaTheme.amber.opacity(0.7)), style: StrokeStyle(lineWidth: 1, dash: [3, 3]))
                    }
                }
                .background(NovaTheme.surfaceMuted)
                .overlay(alignment: .topLeading) { Text("RELATIVE FLUX / PPM").font(.nova(size: 7, weight: .bold, design: .monospaced)).foregroundStyle(NovaTheme.inkTertiary).padding(.leading, 7).padding(.top, 3) }
                .overlay(alignment: .bottomTrailing) {
                    Text("ORBITAL PHASE · \(rows.count.formatted()) BINS · \(rows.reduce(0) { $0 + $1.samples }.formatted()) SAMPLES")
                        .font(.nova(size: 7, weight: .bold, design: .monospaced))
                        .foregroundStyle(NovaTheme.inkTertiary)
                        .padding(6)
                }
            }
        }
    }

    private static func median(_ values: [Double]) -> Double {
        let sorted = values.sorted()
        let middle = sorted.count / 2
        return sorted.count.isMultiple(of: 2) ? (sorted[middle - 1] + sorted[middle]) / 2 : sorted[middle]
    }
}

