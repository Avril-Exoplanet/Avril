    private func decisionChecks(_ candidate: ResultCandidate) -> [EvidenceCheck] {
        let status = candidate.significanceStatus
        let significance: EvidenceCheck
        if status.hasPrefix("skipped") || status == "not_computed" || status == "insufficient_statistics" {
            significance = .init(title: model.t("Red noise / phase null", "红噪声 / 相位零假设"), status: model.t("NOT COMPLETED", "未完成"), detail: status.replacingOccurrences(of: "_", with: " "), state: .unavailable)
        } else if candidate.passesReference == true {
            significance = .init(title: model.t("Red noise / phase null", "红噪声 / 相位零假设"), status: "PASS", detail: significanceDetail(candidate), state: .good)
        } else {
            significance = .init(title: model.t("Red noise / phase null", "红噪声 / 相位零假设"), status: "FAIL", detail: significanceDetail(candidate), state: .bad)
        }

        let holdoutPassed = candidate.raw.value(at: "holdout_verification", "passed")?.boolValue
        let holdout = EvidenceCheck(
            title: model.t("Fixed-ephemeris reproduction", "固定星历复现"),
            status: holdoutPassed == true ? "PASS" : holdoutPassed == false ? "FAIL" : "N/A",
            detail: candidate.raw.value(at: "holdout_verification", "outcome")?.stringValue ?? "not computed",
            state: holdoutPassed == true ? .good : holdoutPassed == false ? .bad : .unavailable
        )

        let gap = candidate.gapDiagnostics
        let gapDominated = gap?["gap_dominated_weak_remainder"]?.boolValue
        let gapCheck = EvidenceCheck(
            title: model.t("Gap support", "缺口支撑"),
            status: gapDominated == true ? model.t("DOMINATED", "缺口主导") : gap != nil ? model.t("CHECKED", "已检查") : "N/A",
            detail: gapDetail(gap),
            state: gapDominated == true ? .bad : gap != nil ? .good : .unavailable
        )

        let pixelStatus = candidate.pixelStatus
        let pixelDetail: String
        if ["on_target", "consistent_on_target"].contains(pixelStatus) {
            pixelDetail = model.t(
                "\(candidate.pixelSectorsAvailable ?? 0) sector(s) localized with the recorded pixel method.",
                "已用记录中的像素方法定位 \(candidate.pixelSectorsAvailable ?? 0) 个区段。"
            )
        } else if pixelStatus == "no_pixel_localization" || pixelStatus == "not_computed" {
            pixelDetail = model.t(
                "NO PIXEL LOCALIZATION. Centroid and crowding checks do not substitute for target-pixel difference imaging.",
                "没有像素定位。质心与拥挤度检查不能替代目标像素差分成像。"
            )
        } else {
            pixelDetail = model.t(
                "\(candidate.pixelSectorsAvailable ?? 0) of \(candidate.pixelSectorsRequested ?? 0) requested sector(s) were available.",
                "请求的 \(candidate.pixelSectorsRequested ?? 0) 个区段中有 \(candidate.pixelSectorsAvailable ?? 0) 个可用。"
            )
        }
        let pixel = EvidenceCheck(
            title: model.t("Pixel localization", "像素定位"),
            status: pixelStatus.uppercased(),
            detail: pixelDetail,
            state: ["on_target", "consistent_on_target"].contains(pixelStatus) ? .good : (pixelStatus.contains("off_target") ? .bad : .unavailable)
        )

        let physical = candidate.raw.value(at: "physical_vetting")
        let physicalPassed = physical?["passed"]?.boolValue
        let vetoes = physical?["vetoes"]?.arrayValue?.compactMap(\.stringValue) ?? []
        let physicalCheck = EvidenceCheck(
            title: model.t("Physical false-positive checks", "物理假阳性检查"),
            status: physicalPassed == true ? "PASS" : !vetoes.isEmpty ? "RISK" : "N/A",
            detail: vetoes.joined(separator: " · ").ifEmpty(physical?["tier"]?.stringValue ?? "not computed"),
            state: physicalPassed == true ? .good : !vetoes.isEmpty ? .bad : .unavailable
        )

        let reference = candidate.raw.value(at: "reference_vetting")
        let referenceAvailable = reference?["available"]?.boolValue
        let warnings = reference?["warnings"]?.arrayValue?.compactMap(\.stringValue) ?? []
        let advisories = reference?["advisories"]?.arrayValue?.compactMap(\.stringValue) ?? []
        let failures = reference?["failures"]?.arrayValue?.compactMap(\.stringValue) ?? []
        let referenceCheck = EvidenceCheck(
            title: model.t("Reference vetter", "参考排假器"),
            status: reference?["status"]?.stringValue?.uppercased() ?? "N/A",
            detail: (failures + warnings + advisories).joined(separator: " · ").ifEmpty(referenceAvailable == true ? "available" : "not computed"),
            state: !failures.isEmpty ? .bad : (!warnings.isEmpty || !advisories.isEmpty) ? .warning : referenceAvailable == true ? .good : .unavailable
        )

        return [significance, holdout, gapCheck, physicalCheck, pixel, referenceCheck]
    }

    private func checkFromPhysical(_ candidate: ResultCandidate, key: String, title: String) -> EvidenceCheck {
        let check = candidate.raw.value(at: "physical_vetting", key)
        let available = check?["available"]?.boolValue
        let veto = check?["veto"]?.boolValue
        let detail: String
        switch key {
        case "odd_even":
            detail = "Δ \(check?["difference_sigma"]?.doubleValue.map { String(format: "%.2fσ", $0) } ?? "—") · odd \(check?["odd_depth_ppm"]?.doubleValue.map { String(format: "%.1f", $0) } ?? "—") ppm · even \(check?["even_depth_ppm"]?.doubleValue.map { String(format: "%.1f", $0) } ?? "—") ppm"
        case "secondary_eclipse":
            detail = "S/N \(check?["snr"]?.doubleValue.map { String(format: "%.2f", $0) } ?? "—") · depth ratio \(check?["depth_ratio"]?.doubleValue.map { String(format: "%.3f", $0) } ?? "—")"
        case "v_shape":
            detail = "ingress \(check?["ingress_fraction"]?.doubleValue.map { String(format: "%.3f", $0) } ?? "—") · Δχ² \(check?["delta_chi2_vs_u"]?.doubleValue.map { String(format: "%.2f", $0) } ?? "—")"
        case "centroid_motion":
            detail = "shift \(check?["shift_pixels"]?.doubleValue.map { String(format: "%.6f px", $0) } ?? "—") · \(check?["significance"]?.doubleValue.map { String(format: "%.2fσ", $0) } ?? "—") · direction \(check?["direction_consistency"]?.doubleValue.map { String(format: "%.2f", $0) } ?? "—")"
        case "neighbor_contamination":
            detail = "CROWDSAP \(check?["crowdsap"]?.doubleValue.map { String(format: "%.4f", $0) } ?? "—") · required eclipse \(check?["required_neighbor_eclipse_fraction"]?.doubleValue.map { String(format: "%.3f", $0) } ?? "—") · mimic \(check?["neighbor_can_mimic"]?.boolValue == true ? "possible" : "not indicated")"
        default:
            detail = available == true ? (veto == true ? model.t("Risk gate triggered", "已触发风险门槛") : model.t("No veto was triggered", "未触发否决门槛")) : model.t("Not computed; not a pass", "未计算，不等于通过")
        }
        return EvidenceCheck(
            title: title,
            status: available == true ? (veto == true ? "RISK" : "CLEAR") : "N/A",
            detail: available == true ? detail : model.t("Not computed; not a pass", "未计算，不等于通过"),
            state: available == true ? (veto == true ? .bad : .good) : .unavailable
        )
    }

    private func significanceDetail(_ candidate: ResultCandidate) -> String {
        let mes = candidate.calibratedMES.map { String(format: "MES %.3f", $0) } ?? "MES —"
        let fap = candidate.phaseNullFAP.map { String(format: "local FAP %.3g", $0) } ?? "local FAP —"
        return "\(candidate.significanceStatus.replacingOccurrences(of: "_", with: " ")) · \(mes) · \(fap)"
    }

    private func gapDetail(_ gap: JSONValue?) -> String {
        guard let gap else { return model.t("Not computed; not a pass", "未计算，不等于通过") }
        let sector = gap["dominant_event_segment"]?.intValue.map { "S\($0)" } ?? "S—"
        let ses = gap["dominant_event_ses_like"]?.doubleValue.map { String(format: "SES %.2f", $0) } ?? "SES —"
        let remainder = gap["combined_without_gap_compromised_events"]?["mes_like"]?.doubleValue.map { String(format: "clean MES %.2f", $0) } ?? "clean MES —"
        return "\(gap["critical_event_count"]?.intValue ?? 0) compromised · \(sector) \(ses) · \(remainder)"
    }

    private func referenceDiagnosticChecks(_ candidate: ResultCandidate) -> [EvidenceCheck] {
        let reference = candidate.raw.value(at: "reference_vetting")
        let modelShift = reference?["model_shift"]
        let coverage = reference?["transit_phase_coverage"]
        let variability = reference?["sinusoidal_variability"]
        let fits = variability?["fits"]?.arrayValue ?? []
        let strongest = fits.compactMap { $0["sigma"]?.doubleValue }.max()
        return [
            EvidenceCheck(
                title: model.t("Model-shift diagnostic", "模型平移诊断"),
                status: modelShift?["available"]?.boolValue == true ? "MEASURED" : "N/A",
                detail: "primary \(modelShift?["primary_dip_sigma"]?.doubleValue.map { String(format: "%.2fσ", $0) } ?? "—") · secondary \(modelShift?["secondary_dip_sigma"]?.doubleValue.map { String(format: "%.2fσ", $0) } ?? "—") · red β \(modelShift?["red_noise_factor"]?.doubleValue.map { String(format: "%.2f", $0) } ?? "—")",
                state: modelShift?["available"]?.boolValue == true ? .neutral : .unavailable
            ),
            EvidenceCheck(
                title: model.t("Transit phase coverage", "凌星相位覆盖"),
                status: coverage?["available"]?.boolValue == true ? (coverage?["fraction"]?.doubleValue.map { String(format: "%.0f%%", $0 * 100) } ?? "MEASURED") : "N/A",
                detail: "\(coverage?["occupied_bins"]?.intValue ?? 0) / \(coverage?["total_bins"]?.intValue ?? 0) phase bins",
                state: coverage?["available"]?.boolValue == true ? .good : .unavailable
            ),
            EvidenceCheck(
                title: model.t("Sinusoidal variability", "正弦变化"),
                status: variability?["available"]?.boolValue == true ? (strongest.map { String(format: "MAX %.2fσ", $0) } ?? "MEASURED") : "N/A",
                detail: "\(fits.count) timescales · \(variability?["cadences_used"]?.intValue ?? 0) cadences",
                state: variability?["available"]?.boolValue == true ? ((strongest ?? 0) >= (variability?["warning_sigma"]?.doubleValue ?? 3) ? .warning : .good) : .unavailable
            ),
        ]
    }

    private func unavailable(_ message: String) -> some View {
        Text(message)
            .font(.nova(size: 10))
            .foregroundStyle(NovaTheme.inkTertiary)
            .frame(maxWidth: .infinity, minHeight: 90)
            .background(NovaTheme.surfaceMuted)
    }
