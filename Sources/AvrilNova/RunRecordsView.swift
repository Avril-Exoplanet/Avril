import AppKit
import SwiftUI

private enum RecordCandidateFilter: String, CaseIterable, Identifiable {
    case all, high, review, risk
    var id: String { rawValue }
}

private enum RecordReportTab: String, CaseIterable, Identifiable {
    case overview, folds, events, timeline, vetting, harmonics, execution, expert, ledger
    var id: String { rawValue }
}

struct RunRecordsView: View {
    @EnvironmentObject private var model: AppModel
    @State private var candidateFilter: RecordCandidateFilter = .all
    @State private var reportTab: RecordReportTab = .overview
    @State private var executionSearch = ""
    @State private var timelineLaneLimit = 25

    private var selectedRecord: RunRecordSummary? {
        guard let id = model.selectedRunID else { return nil }
        return model.runRecords.first { $0.id == id }
    }

    private var allCandidates: [ResultCandidate] {
        model.selectedScienceResult?.auditCandidates ?? []
    }

    private var filteredCandidates: [ResultCandidate] {
        allCandidates.filter { candidate in
            switch candidateFilter {
            case .all: true
            case .high: candidate.priority == "high_priority_follow_up_candidate"
            case .review: candidate.priority == "manual_review_required"
            case .risk:
                candidate.priority == "low_priority_or_false_alarm_risk"
                    || !candidate.riskFlags.isEmpty
                    || candidate.passesReference != true
            }
        }
    }

    private var selectedCandidate: ResultCandidate? {
        if let id = model.selectedCandidateID,
           let candidate = allCandidates.first(where: { $0.id == id }) {
            if let detail = model.selectedCandidateDetail,
               detail.candidateID == candidate.candidateID {
                return detail
            }
            return candidate
        }
        return filteredCandidates.first
    }

    var body: some View {
        VStack(spacing: 0) {
            reportHeader
            Rectangle().fill(NovaTheme.border).frame(height: 1)

            if model.runRecords.isEmpty, let error = model.scienceResultError, !model.isLoadingRunRecords {
                EmptyScienceState(
                    symbol: "exclamationmark.triangle",
                    title: model.t("Run archive unavailable", "运行档案不可用"),
                    message: error
                )
            } else if model.runRecords.isEmpty && !model.isLoadingRunRecords {
                EmptyScienceState(
                    symbol: "doc.text.magnifyingglass",
                    title: model.t("No run records", "暂无运行记录"),
                    message: model.t(
                        "Completed and interrupted Avril runs will remain available here after the application restarts.",
                        "Avril 的完成任务与中断任务会在软件重启后继续保留在这里。"
                    )
                )
            } else {
                HSplitView {
                    recordBrowser
                        .frame(minWidth: 235, idealWidth: 270, maxWidth: 320)
                    reportWorkspace
                        .frame(minWidth: 520, maxWidth: .infinity)
                    decisionInspector
                        .frame(minWidth: 250, idealWidth: 286, maxWidth: 330)
                }
            }
        }
        .background(NovaTheme.canvas)
        .task {
            if model.runRecords.isEmpty {
                await model.loadRunRecords(loadSelection: false)
            }
            if model.selectedScienceResult == nil, let runID = model.selectedRunID {
                await model.loadScienceResult(runID: runID)
            }
            if model.selectedExecutionLog == nil, let runID = model.selectedRunID {
                await model.loadExecutionLog(runID: runID)
            }
            if model.selectedScienceTimeline == nil, let runID = model.selectedRunID {
                await model.loadScienceTimeline(runID: runID)
            }
        }
        .onChange(of: candidateFilter) { _, _ in selectFirstVisibleCandidateIfNeeded() }
        .onChange(of: model.selectedScienceResult?.canonicalCandidateCount) { _, _ in
            selectFirstVisibleCandidateIfNeeded()
        }
    }

    private var reportHeader: some View {
        HStack(spacing: 14) {
            SectionHeading(
                eyebrow: model.t("Persistent evidence archive", "持久化证据档案"),
                title: model.t("Run Records", "运行记录"),
                detail: model.t(
                    "Inspect every run, signal ledger, diagnostic gate and reproducibility field generated by Avril V3.",
                    "查看 Avril V3 生成的每次运行、信号记录、诊断门槛与可复现性字段。"
                )
            )
            Spacer(minLength: 12)
            if let record = selectedRecord, record.isComplete {
                Menu {
                    Button {
                        model.exportRunArtifact(runID: record.id, kind: .candidatePDF)
                    } label: {
                        Label(model.t("Candidate science PDF", "候选科学 PDF"), systemImage: "doc.richtext")
                    }
                    Divider()
                    Button {
                        model.exportRunArtifact(runID: record.id, kind: .resultJSON)
                    } label: {
                        Label(model.t("Complete result JSON", "完整结果 JSON"), systemImage: "doc.text")
                    }
                    Button {
                        model.exportRunArtifact(runID: record.id, kind: .fullAudit)
                    } label: {
                        Label(model.t("Full audit archive", "完整审计档案"), systemImage: "archivebox")
                    }
                    Button {
                        model.exportRunArtifact(runID: record.id, kind: .auditCSV)
                    } label: {
                        Label(model.t("Audit ledger CSV", "审计记录 CSV"), systemImage: "tablecells")
                    }
                } label: {
                    Label(model.t("Export Report", "导出报告"), systemImage: "square.and.arrow.up")
                }
                .buttonStyle(SecondaryButtonStyle(compact: true))
                .disabled(model.selectedScienceResult == nil)
            }
            Button { Task { await model.loadRunRecords(loadSelection: false) } } label: {
                Label(model.t("Refresh", "刷新"), systemImage: "arrow.clockwise")
            }
            .buttonStyle(SecondaryButtonStyle(compact: true))
            .disabled(model.isExportingRunArtifact)
        }
        .padding(.horizontal, 18)
        .frame(height: 82)
        .background(NovaTheme.surface)
    }

    private var recordBrowser: some View {
        VStack(spacing: 0) {
            browserHeader(
                model.t("RUN HISTORY", "运行历史"),
                detail: model.t("\(model.runRecords.count) preserved sessions", "\(model.runRecords.count) 个已保留会话")
            )
            ScrollView {
                LazyVStack(spacing: 6) {
                    ForEach(model.runRecords) { record in
                        runRow(record)
                    }
                }
                .padding(8)
            }
            .frame(minHeight: 150, idealHeight: 190, maxHeight: 230)

            Rectangle().fill(NovaTheme.border).frame(height: 1)
            browserHeader(
                model.t("SIGNAL LEDGER", "信号记录"),
                detail: model.t("\(filteredCandidates.count) visible / \(allCandidates.count) audit rows", "\(filteredCandidates.count) 条可见 / \(allCandidates.count) 条审计")
            )
            candidateFilterBar
            if model.isLoadingScienceResult {
                VStack(spacing: 10) {
                    ProgressView()
                    Text(model.t("Loading the scientific evidence document…", "正在读取科学证据文档…"))
                        .font(.nova(size: 10))
                        .foregroundStyle(NovaTheme.inkTertiary)
                }
                .frame(maxWidth: .infinity, maxHeight: .infinity)
            } else {
                ScrollView {
                    LazyVStack(spacing: 3) {
                        ForEach(filteredCandidates) { candidate in
                            candidateRow(candidate)
                        }
                    }
                    .padding(7)
                }
            }
        }
        .background(NovaTheme.surface)
        .overlay(alignment: .trailing) { Rectangle().fill(NovaTheme.border).frame(width: 1) }
    }

    private func browserHeader(_ title: String, detail: String) -> some View {
        HStack {
            VStack(alignment: .leading, spacing: 2) {
                Text(title).font(.nova(size: 9, weight: .bold)).tracking(0.8).foregroundStyle(NovaTheme.inkSecondary)
                Text(detail).font(.nova(size: 9)).foregroundStyle(NovaTheme.inkTertiary).lineLimit(1)
            }
            Spacer()
        }
        .padding(.horizontal, 12)
        .frame(height: 47)
        .background(NovaTheme.surfaceStrong)
    }

    private func runRow(_ record: RunRecordSummary) -> some View {
        let selected = model.selectedRunID == record.id
        return Button {
            withAnimation(.easeInOut(duration: 0.2)) {
                reportTab = .overview
                candidateFilter = .all
                model.selectRun(record)
            }
        } label: {
            VStack(alignment: .leading, spacing: 6) {
                HStack(spacing: 7) {
                    Circle().fill(runTint(record.status)).frame(width: 7, height: 7)
                    Text(record.target).font(.nova(size: 11, weight: .semibold)).foregroundStyle(NovaTheme.ink)
                    Spacer()
                    Text(runStatus(record.status))
                        .font(.nova(size: 8, weight: .bold))
                        .foregroundStyle(runTint(record.status))
                }
                HStack(spacing: 6) {
                    Text(recordDate(record)).lineLimit(1)
                    Spacer()
                    Text(model.t("\(record.auditRows) audit", "\(record.auditRows) 条审计"))
                    if let seconds = record.computeSeconds { Text(duration(seconds)) }
                }
                .font(.nova(size: 8.5, design: .monospaced))
                .foregroundStyle(NovaTheme.inkTertiary)
            }
            .padding(9)
            .background(selected ? NovaTheme.accentSoft : NovaTheme.surfaceMuted)
            .clipShape(RoundedRectangle(cornerRadius: 6, style: .continuous))
            .overlay {
                RoundedRectangle(cornerRadius: 6).stroke(selected ? NovaTheme.accent.opacity(0.55) : NovaTheme.border, lineWidth: 1)
            }
            .overlay(alignment: .leading) {
                if selected { Rectangle().fill(NovaTheme.accent).frame(width: 3).padding(.vertical, 5) }
            }
        }
        .buttonStyle(.plain)
    }

    private var candidateFilterBar: some View {
        ScrollView(.horizontal, showsIndicators: false) {
            HStack(spacing: 3) {
                ForEach(RecordCandidateFilter.allCases) { filter in
                    Button(filterLabel(filter)) { candidateFilter = filter }
                        .buttonStyle(.plain)
                        .font(.nova(size: 8.5, weight: candidateFilter == filter ? .bold : .medium))
                        .foregroundStyle(candidateFilter == filter ? .white : NovaTheme.inkSecondary)
                        .padding(.horizontal, 7)
                        .frame(height: 25)
                        .background(candidateFilter == filter ? NovaTheme.accent : NovaTheme.surfaceMuted)
                        .clipShape(RoundedRectangle(cornerRadius: 4))
                }
            }
            .fixedSize(horizontal: true, vertical: false)
        }
        .padding(7)
        .background(NovaTheme.surface)
    }

    private func candidateRow(_ candidate: ResultCandidate) -> some View {
        let selected = selectedCandidate?.id == candidate.id
        return Button {
            withAnimation(.easeInOut(duration: 0.2)) {
                model.selectCandidate(candidate)
                reportTab = .overview
            }
        } label: {
            HStack(spacing: 8) {
                Text("#\(candidate.rank ?? 0)")
                    .font(.nova(size: 9, weight: .semibold, design: .monospaced))
                    .foregroundStyle(NovaTheme.inkTertiary)
                    .frame(width: 27, alignment: .trailing)
                VStack(alignment: .leading, spacing: 3) {
                    Text(candidate.candidateID)
                        .font(.nova(size: 10.5, weight: .semibold, design: .monospaced))
                        .foregroundStyle(NovaTheme.ink)
                    Text(candidate.periodDays.map { String(format: "%.7f d", $0) } ?? model.t("Period unavailable", "周期不可用"))
                        .font(.nova(size: 9, design: .monospaced))
                        .foregroundStyle(NovaTheme.inkSecondary)
                }
                Spacer(minLength: 3)
                Text(priorityCompact(candidate.priority))
                    .font(.nova(size: 7.5, weight: .bold))
                    .foregroundStyle(priorityTint(candidate.priority))
                    .padding(.horizontal, 5)
                    .frame(height: 18)
                    .background(priorityTint(candidate.priority).opacity(0.10))
                    .clipShape(RoundedRectangle(cornerRadius: 3))
            }
            .padding(.horizontal, 8)
            .frame(height: 52)
            .background(selected ? NovaTheme.accentSoft : Color.clear)
            .overlay(alignment: .leading) {
                if selected { Rectangle().fill(NovaTheme.accent).frame(width: 3).padding(.vertical, 5) }
            }
        }
        .buttonStyle(.plain)
    }

    @ViewBuilder
    private var reportWorkspace: some View {
        if let result = model.selectedScienceResult, let record = selectedRecord {
            VStack(spacing: 0) {
                runSummary(record: record, result: result)
                if let candidate = selectedCandidate {
                    candidateTitle(candidate)
                    reportTabBar
                    ScrollView {
                        reportContent(candidate: candidate, result: result)
                            .id("\(candidate.id)-\(reportTab.rawValue)")
                            .transition(.opacity.combined(with: .move(edge: .trailing)))
                            .padding(14)
                    }
                    .animation(.easeInOut(duration: 0.2), value: reportTab)
                    .animation(.easeInOut(duration: 0.2), value: candidate.id)
                } else {
                    EmptyScienceState(
                        symbol: filteredCandidates.isEmpty ? "line.3.horizontal.decrease.circle" : "scope",
                        title: filteredCandidates.isEmpty ? model.t("No rows match this filter", "当前筛选没有记录") : model.t("No signal selected", "未选择信号"),
                        message: filteredCandidates.isEmpty ? model.t("Choose another science-review filter; no audit rows are hidden or deleted.", "请选择其他科学复核筛选；审计记录不会被隐藏删除。") : model.t("Choose an audit row from the signal ledger.", "请从信号记录中选择一条审计记录。")
                    )
                }
            }
            .background(NovaTheme.canvas)
        } else if let record = selectedRecord, !record.isComplete {
            incompleteRunReport(record)
        } else if let error = model.scienceResultError {
            EmptyScienceState(symbol: "exclamationmark.triangle", title: model.t("Result unavailable", "结果不可用"), message: error)
        } else {
            EmptyScienceState(
                symbol: "waveform.path.ecg.rectangle",
                title: model.t("Select a completed run", "请选择已完成的运行"),
                message: model.t("The complete candidate evidence document is loaded only when needed.", "完整候选证据文档只会在需要时读取。")
            )
        }
    }

    private func incompleteRunReport(_ record: RunRecordSummary) -> some View {
        ScrollView {
            VStack(alignment: .leading, spacing: 14) {
            HStack(spacing: 12) {
                Image(systemName: record.status == "cancelled" ? "stop.circle" : "exclamationmark.triangle")
                    .font(.nova(size: 26, weight: .light))
                    .foregroundStyle(runTint(record.status))
                VStack(alignment: .leading, spacing: 3) {
                    Text(record.target).font(.nova(size: 20, weight: .semibold))
                    Text(runStatus(record.status)).font(.nova(size: 9, weight: .bold, design: .monospaced)).foregroundStyle(runTint(record.status))
                }
                Spacer()
            }
            EvidencePropertyPanel(
                title: model.t("Run state", "运行状态"),
                subtitle: model.t("preserved execution metadata", "已保留执行元数据"),
                rows: [
                    (model.t("Stage", "阶段"), record.stage ?? "—"),
                    (model.t("Progress", "进度"), record.percent.map { String(format: "%.1f%%", $0) } ?? "—"),
                    (model.t("Message", "消息"), record.message ?? "—"),
                    (model.t("Error", "错误"), record.error ?? "—"),
                    (model.t("Engine", "引擎"), record.engine ?? "—"),
                    (model.t("Backend", "后端"), record.backend ?? "—"),
                    (model.t("Source", "数据源"), record.source ?? "—"),
                    (model.t("Pixel follow-up", "像素复核"), record.pixels ?? "none"),
                    (model.t("Queue time", "排队耗时"), record.queueSeconds.map(duration) ?? "—"),
                    (model.t("Compute time", "计算耗时"), record.computeSeconds.map(duration) ?? "—"),
                    (model.t("Total time", "总耗时"), record.totalSeconds.map(duration) ?? "—"),
                    (model.t("Created", "创建时间"), recordTimestamp(record.createdAt)),
                    (model.t("Updated", "更新时间"), recordTimestamp(record.updatedAt)),
                ]
            )
            Text(model.t(
                "This run remains in the archive for reproducibility. It did not produce a complete scientific result, so no candidate interpretation is shown.",
                "该运行会为可复现性继续保留在档案中。它没有生成完整科学结果，因此不会显示候选解读。"
            ))
            .font(.nova(size: 10)).foregroundStyle(NovaTheme.inkSecondary)
                executionLogReport()
            }
            .padding(18)
        }
        .background(NovaTheme.canvas)
    }

    private func runSummary(record: RunRecordSummary, result: ScienceResultDocument) -> some View {
        HStack(spacing: 0) {
            summaryCell(model.t("TARGET", "目标"), record.target)
            summaryCell(model.t("SEARCHED SECTORS", "搜索区段"), "\(result.segments.count)", note: result.segments.map(String.init).joined(separator: " · "))
            summaryCell(model.t("AUDIT ROWS", "审计记录"), "\(result.auditCandidates.count)", note: model.t("not a planet count", "不是行星数量"))
            summaryCell(model.t("RUNTIME", "运行时间"), record.computeSeconds.map(duration) ?? "—")
            summaryCell(model.t("ENGINE", "引擎"), result.releaseID ?? result.engineVersion ?? "AVRIL V3", note: record.backend ?? "auto")
        }
        .frame(height: 72)
        .background(NovaTheme.surfaceStrong)
        .overlay(alignment: .bottom) { Rectangle().fill(NovaTheme.border).frame(height: 1) }
    }

    private func summaryCell(_ label: String, _ value: String, note: String? = nil) -> some View {
        VStack(alignment: .leading, spacing: 3) {
            Text(label).font(.nova(size: 7.5, weight: .bold)).tracking(0.6).foregroundStyle(NovaTheme.inkTertiary)
            Text(value).font(.nova(size: 13, weight: .semibold, design: .monospaced)).foregroundStyle(NovaTheme.ink).lineLimit(1)
            if let note { Text(note).font(.nova(size: 8)).foregroundStyle(NovaTheme.inkTertiary).lineLimit(1) }
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .leading)
        .padding(.horizontal, 12)
        .overlay(alignment: .trailing) { Rectangle().fill(NovaTheme.border).frame(width: 1).padding(.vertical, 10) }
    }

    private func candidateTitle(_ candidate: ResultCandidate) -> some View {
        HStack(spacing: 13) {
            Text("#\(candidate.rank ?? 0)")
                .font(.nova(size: 14, weight: .bold, design: .monospaced))
                .foregroundStyle(.white)
                .frame(width: 48, height: 38)
                .background(NovaTheme.accent)
                .clipShape(RoundedRectangle(cornerRadius: 5))
            VStack(alignment: .leading, spacing: 3) {
                Text(candidate.candidateID.uppercased())
                    .font(.nova(size: 8.5, weight: .bold, design: .monospaced))
                    .tracking(0.7)
                    .foregroundStyle(NovaTheme.accentDark)
                HStack(alignment: .firstTextBaseline, spacing: 6) {
                    Text(candidate.periodDays.map { String(format: "%.8f", $0) } ?? "—")
                        .font(.nova(size: 22, weight: .semibold, design: .rounded))
                    Text(model.t("days", "天")).font(.nova(size: 10)).foregroundStyle(NovaTheme.inkSecondary)
                }
                Text(plainConclusion(candidate)).font(.nova(size: 9.5)).foregroundStyle(NovaTheme.inkSecondary).lineLimit(1)
            }
            Spacer()
            VStack(alignment: .trailing, spacing: 4) {
                Text(model.t("SCIENCE REVIEW", "科学复核"))
                    .font(.nova(size: 7.5, weight: .bold)).tracking(0.65).foregroundStyle(NovaTheme.inkTertiary)
                StatusPill(label: priorityLabel(candidate.priority), tint: priorityTint(candidate.priority))
                HStack(spacing: 5) {
                    if model.isLoadingCandidateDetail { ProgressView().controlSize(.mini) }
                    Text(model.isLoadingCandidateDetail
                         ? model.t("loading full audit row", "正在加载完整审计记录")
                         : model.t("classification, not planet probability", "这是分类，不是行星概率"))
                }
                    .font(.nova(size: 8)).foregroundStyle(NovaTheme.inkTertiary)
            }
        }
        .padding(.horizontal, 14)
        .frame(height: 84)
        .background(NovaTheme.surface)
        .overlay(alignment: .bottom) { Rectangle().fill(NovaTheme.border).frame(height: 1) }
    }

    private var reportTabBar: some View {
        ScrollView(.horizontal, showsIndicators: false) {
            HStack(spacing: 2) {
                ForEach(RecordReportTab.allCases) { tab in
                    Button(tabLabel(tab)) { reportTab = tab }
                        .buttonStyle(.plain)
                        .font(.nova(size: 9, weight: reportTab == tab ? .semibold : .medium))
                        .foregroundStyle(reportTab == tab ? NovaTheme.accentDark : NovaTheme.inkSecondary)
                        .padding(.horizontal, 10)
                        .frame(height: 34)
                        .background(reportTab == tab ? NovaTheme.accentSoft : Color.clear)
                        .overlay(alignment: .bottom) {
                            if reportTab == tab { Rectangle().fill(NovaTheme.accent).frame(height: 2) }
                        }
                }
            }
            .fixedSize(horizontal: true, vertical: false)
        }
        .padding(.horizontal, 10)
        .background(NovaTheme.surface)
        .overlay(alignment: .bottom) { Rectangle().fill(NovaTheme.border).frame(height: 1) }
    }

    @ViewBuilder
    private func reportContent(candidate: ResultCandidate, result: ScienceResultDocument) -> some View {
        switch reportTab {
        case .overview: overview(candidate: candidate, result: result)
        case .folds: folds(candidate)
        case .events: events(candidate)
        case .timeline: scienceTimelineReport()
        case .vetting: vetting(candidate)
        case .harmonics: harmonics(candidate)
        case .execution: executionLogReport()
        case .expert: expert(candidate)
        case .ledger: auditLedger(result.auditCandidates)
        }
    }

    private func overview(candidate: ResultCandidate, result: ScienceResultDocument) -> some View {
        return VStack(spacing: 12) {
            formalReportMetadata(result: result)
            EvidenceFunnelView(result: result)
            LazyVGrid(columns: Array(repeating: GridItem(.flexible(), spacing: 8), count: 3), spacing: 8) {
                reportMetric(model.t("PERIOD", "周期"), candidate.periodDays.map { String(format: "%.8f d", $0) } ?? "—", "LOCKED EPHEMERIS")
                reportMetric(model.t("EPOCH", "历元"), candidate.epochBTJD.map { String(format: "%.6f BTJD", $0) } ?? "—", "FIXED")
                reportMetric(model.t("DURATION", "时长"), candidate.durationHours.map { String(format: "%.3f h", $0) } ?? "—", "TRANSIT WINDOW")
                reportMetric(model.t("DEPTH", "深度"), candidate.depthPPM.map { String(format: "%.1f ppm", $0) } ?? "—", "ROBUST ESTIMATE")
                reportMetric(model.t("RED-NOISE MES", "红噪声 MES"), candidate.calibratedMES.map { String(format: "%.3f", $0) } ?? model.t("NOT RUN", "未运行"), candidate.significanceStatus.uppercased())
                reportMetric(model.t("EVENT SUPPORT", "事件支持"), supportText(candidate), model.t("fixed ephemeris", "固定星历"))
                reportMetric(model.t("EVENT COHERENCE S/N", "事件一致性信噪比"), candidate.eventCoherenceSNR.map { String(format: "%.3f", $0) } ?? "—", model.t("not red-noise MES", "不是红噪声 MES"))
                reportMetric(model.t("PHASE-NULL FAP", "相位零假设 FAP"), candidate.phaseNullFAP.map { String(format: "%.3g", $0) } ?? "—", model.t("local empirical", "局部经验值"))
                reportMetric(model.t("LOOK-ELSEWHERE FAP", "全局试验 FAP"), candidate.lookElsewhereFAP.map { String(format: "%.3g", $0) } ?? "—", model.t("estimated trial factor", "估计试验因子"))
            }
            HStack(alignment: .top, spacing: 10) {
                EvidenceReasonPanel(
                    title: model.t("Why it received this classification", "为什么进入这个等级"),
                    subtitle: "TRACEABLE REASONS",
                    rows: reasonRows(candidate),
                    tint: NovaTheme.green
                )
                EvidenceReasonPanel(
                    title: model.t("Risks and incomplete checks", "风险与未完成项"),
                    subtitle: "NOT A CONFIRMATION",
                    rows: riskRows(candidate),
                    tint: NovaTheme.amber
                )
            }
        }
    }

    private func formalReportMetadata(result: ScienceResultDocument) -> some View {
        let record = selectedRecord
        let meaningful = result.annotationInt("meaningful_candidate_funnel", "meaningful_candidates")
        let shortCircuited = result.annotationInt("meaningful_candidate_funnel", "short_circuited_candidates")
        let exactNull = result.annotationInt("detection_significance", "exactly_evaluated_candidate_count")
        let catalogAvailable = result.scienceAnnotation?.value(at: "meaningful_candidate_funnel", "catalog_available")?.boolValue
        let catalogRows = result.annotationInt("meaningful_candidate_funnel", "catalog_rows")
        return VStack(spacing: 10) {
            HStack(alignment: .top, spacing: 10) {
                EvidencePropertyPanel(
                    title: model.t("Report identity", "报告标识"),
                    subtitle: model.t("persistent run provenance", "持久化运行来源"),
                    rows: [
                        (model.t("Target", "目标"), result.target ?? record?.target ?? "—"),
                        (model.t("TIC identifier", "TIC 编号"), result.ticID.map(String.init) ?? "—"),
