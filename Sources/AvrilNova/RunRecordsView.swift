    private func plainConclusion(_ candidate: ResultCandidate) -> String {
        if candidate.gapDiagnostics?["gap_dominated_weak_remainder"]?.boolValue == true {
            let sector = candidate.gapDiagnostics?["dominant_event_segment"]?.intValue.map { "Sector \($0)" } ?? model.t("one event", "一个事件")
            let remainder = candidate.gapDiagnostics?["combined_without_gap_compromised_events"]?["mes_like"]?.doubleValue.map { String(format: "%.2f", $0) } ?? "—"
            return model.t(
                "The strongest evidence is dominated by a gap-compromised event in \(sector); the remaining clean events give MES-like \(remainder), so this signal is downgraded for manual review.",
                "最强证据主要由 \(sector) 的缺测边界受损事件支撑；剔除后干净事件的 MES-like 为 \(remainder)，因此该信号已降级为人工复核。"
            )
        }
        if candidate.passesReference == true {
            return model.t(
                "The locked ephemeris repeats across independent data and passes the current red-noise reference; pixel origin, catalog novelty and independent astrophysical confirmation are still required.",
                "锁定星历已在独立数据中复现，并通过当前红噪声参考门；仍需完成像素来源、目录新颖性与独立天体物理确认。"
            )
        }
        if candidate.significanceStatus == "below_7p1_mes_like_reference" {
            return model.t(
                "The signal was measured with the full red-noise and phase-null test but did not reach the 7.1 MES-like reference. It remains in the audit ledger, not as a high-confidence candidate.",
                "该信号已完成红噪声与相位零假设检验，但未达到 7.1 MES-like 参考门；它会保留在审计记录中，但不是高置信候选。"
            )
        }
        if candidate.raw.value(at: "holdout_verification", "passed")?.boolValue == true {
            return model.t(
                "The same period and epoch are supported in multiple time blocks, but one or more decisive checks were skipped or remain incomplete. Human review is required.",
